-- Banco de dados: Supabase (PostgreSQL)
-- Tabela de livros favoritos
--
-- Este arquivo documenta a estrutura e as politicas RLS.
-- ATENCAO: a tabela e as politicas ja foram criadas no Supabase.
-- Nao execute este script novamente no banco atual sem necessidade.

CREATE TABLE IF NOT EXISTS public.favoritos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz DEFAULT now(),
    titulo text NOT NULL,
    autor text,
    ano_publicacao integer,
    capa_id bigint,
    openlibrary_key text
);

-- Habilita a seguranca em nivel de linha
ALTER TABLE public.favoritos ENABLE ROW LEVEL SECURITY;

-- Permite que visitantes consultem favoritos
CREATE POLICY "Permitir leitura de favoritos"
ON public.favoritos
AS PERMISSIVE
FOR SELECT
TO anon
USING (true);

-- Permite que visitantes adicionem favoritos
CREATE POLICY "Permitir adicionar favoritos"
ON public.favoritos
AS PERMISSIVE
FOR INSERT
TO anon
WITH CHECK (true);

-- Permite que visitantes excluam favoritos
CREATE POLICY "Permitir excluir favoritos"
ON public.favoritos
AS PERMISSIVE
FOR DELETE
TO anon
USING (true);
